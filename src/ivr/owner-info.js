export const OWNER_OPTIONS = ['לִשְׁמִיעָה חוֹזֶרֶת הַקֵּשׁ 1', 'לַתַּפְרִיט הָרָאשִׁי הַקֵּשׁ 2'];

const BACK_TO_MENU = 'חוֹזְרִים לַתַּפְרִיט הָרָאשִׁי';

// המעבר מהתפריט הראשי לשלוחת ההקראה האיטית. s.back: בחזרה לשלוחה הראשית מציגים את התפריט הראשי (כמו אחרי "אין מענה")
export function goToOwnerExt(s, ext) {
  s.ownerArrive = true;
  s.back = true;
  return goToFolder(ext, 'הוֹרָאוֹת לְבַעֲלֵי אוּלָם');
}

// תשובת השרת לשלוחת ההקראה האיטית. הערכים כאן נקראים own1, own2... (לא v1...) כדי לא להתנגש בתפריט הראשי,
// וכל הקשה מקבלת שם חדש כי ימות שולחת בכל פנייה את כל הערכים שנאספו בשיחה.
export function ownerReply(s, q) {
  let note = null;
  if (s.ownerArrive || !s.ownerN) {
    s.ownerArrive = false;                                   // הגענו עכשיו מהתפריט הראשי
  } else {
    const answer = String(lastValue(q[`own${s.ownerN}`]) ?? '').trim();
    if (answer === '2' || answer.includes('*')) {
      s.back = true;
      return goToFolder('/', BACK_TO_MENU);
    }
    if (!answer) note = 'לֹא נִשְׁמְעָה תְּשׁוּבָה';
    else if (answer !== '1') note = 'בְּחִירָה לֹא תְּקִינָה';
  }
  s.ownerN = (s.ownerN ?? 0) + 1;
  return `read=${say([note, ...OWNER_PARTS, ...OWNER_OPTIONS])}=own${s.ownerN},no,${tapOptions(1)}`;
}

// שרת שאותחל באמצע השיחה (אין מצב): חוזרים לשלוחה הראשית, שמתחילה שיחה מחדש
export const ownerRestart = () => goToFolder('/', BACK_TO_MENU);
